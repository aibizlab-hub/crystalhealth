function openLightbox(id, i){
  const p = PRODUCTS.find(x=>x.id===id); if(!p) return;
  const gal = (p.gallery && p.gallery.length) ? p.gallery : [p.img];
  const lb = document.getElementById('lightbox') || (()=>{ const d=document.createElement('div'); d.id='lightbox'; d.className='lightbox'; d.innerHTML=`<button class="lb-x" aria-label="close">×</button><button class="lb-p" aria-label="prev">‹</button><figure><img alt=""><figcaption></figcaption></figure><button class="lb-n" aria-label="next">›</button>`; document.body.appendChild(d); return d; })();
  lb.dataset.id = id; lb.dataset.i = i;
  lbGrid = gal;
  lbSet(lb);
  lb.classList.add('on');
  document.body.classList.add('lb-open');
}
let lbGrid = [];
function lbSet(lb){
  const p = PRODUCTS.find(x=>x.id===lb.dataset.id); if(!p) return;
  const i = parseInt(lb.dataset.i||'0',10);
  const gal = (p.gallery && p.gallery.length) ? p.gallery : [p.img];
  lbGrid = gal;
  lb.querySelector('img').src = IMG(gal[i]);
  lb.querySelector('figcaption').textContent = `${p.name[curLang]}　${i+1} / ${gal.length}`;
  lb.querySelector('.lb-p').style.visibility = gal.length>1 ? 'visible':'hidden';
  lb.querySelector('.lb-n').style.visibility = gal.length>1 ? 'visible':'hidden';
}
function lbStep(d){
  const lb = document.getElementById('lightbox'); if(!lb) return;
  const n = lbGrid.length; if(n<2) return;
  lb.dataset.i = ((parseInt(lb.dataset.i,10) + d) % n + n) % n;
  lbSet(lb);
}
function closeLightbox(){ const lb=document.getElementById('lightbox'); if(lb) lb.classList.remove('on'); document.body.classList.remove('lb-open'); }
document.addEventListener('click', function(e){
  const lb = document.getElementById('lightbox');
  const tgt = e.target.closest ? e.target.closest('[data-gal]') : null;
  if(tgt){ e.preventDefault(); openLightbox(tgt.dataset.gal, parseInt(tgt.dataset.i||'0',10)); return; }
  if(!lb || !lb.classList.contains('on')) return;
  if(e.target.classList.contains('lb-x') || e.target === lb) closeLightbox();
  else if(e.target.classList.contains('lb-p')) lbStep(-1);
  else if(e.target.classList.contains('lb-n')) lbStep(1);
});
document.addEventListener('keydown', function(e){
  const lb = document.getElementById('lightbox'); if(!lb || !lb.classList.contains('on')) return;
  if(e.key==='Escape') closeLightbox();
  else if(e.key==='ArrowLeft') lbStep(-1);
  else if(e.key==='ArrowRight') lbStep(1);
});

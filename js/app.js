function closeNav(){
  document.body.classList.remove('nav-open');
  const sc=document.querySelector('.nav-scrim');
  if(sc){ sc.classList.remove('on'); setTimeout(()=>sc.remove(),240); }
}
function toggleNav(){
  const on = !document.body.classList.contains('nav-open');
  document.body.classList.toggle('nav-open', on);
  const nl = document.querySelector('.nav-links');
  if(on){
    let sc = document.querySelector('.nav-scrim');
    if(!sc){
      sc = document.createElement('div');
      sc.className = 'nav-scrim';
      sc.addEventListener('click', closeNav);
      document.body.appendChild(sc);
    }
    requestAnimationFrame(()=>sc.classList.add('on'));
  } else {
    closeNav();
  }
  if(nl) nl.scrollTop = 0;
}
